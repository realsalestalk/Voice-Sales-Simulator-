# Generates every narration line in js/steps.js as audio, plus mouth-sync envelopes and
# estimated word timings, and writes js/voice-lines.js.
# Usage: python3 tools/build_voice.py [workers]
# Requires: kokoro-onnx, soundfile, ffmpeg (with rubberband), node. See tools/samvoice.py.
import hashlib, json, os, re, subprocess, sys, struct, math
from concurrent.futures import ProcessPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, 'assets', 'voice')
sys.path.insert(0, os.path.join(ROOT, 'tools'))

def lines():
    js = "import('./js/steps.js').then(m=>{const s=new Set();for(const st of m.STEPS)for(const k of ['go','tap','say'])for(const p of st[k]||[])if(p.tts)s.add(p.tts);console.log(JSON.stringify([...s]))})"
    return json.loads(subprocess.run(['node', '-e', js], cwd=ROOT, capture_output=True, text=True, check=True).stdout)

def lid(text): return hashlib.sha1(text.encode()).hexdigest()[:12]

def gen(text):
    import samvoice
    path = os.path.join(OUT_DIR, lid(text) + '.mp3')
    if not os.path.exists(path): samvoice.say(text, path)
    return text

def syl(w):
    w = re.sub(r'[^a-z]', '', w.lower())
    n = len(re.findall(r'[aeiouy]+', w)) - (1 if re.search(r'[^aeiou]e$', w) else 0)
    return max(1, n)

def analyse(text):
    path = os.path.join(OUT_DIR, lid(text) + '.mp3')
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', '8000', '-f', 's16le', '-'], capture_output=True, check=True).stdout
    n = len(raw) // 2; a = struct.unpack('<%dh' % n, raw); hop = 160  # 50 fps
    env = []
    for i in range(0, n, hop):
        seg = a[i:i + hop]; env.append(math.sqrt(sum(x * x for x in seg) / max(1, len(seg))) / 32768)
    m = max(env) or 1
    env = [round(min(1, (e / m) ** 0.7), 2) for e in env]
    dur = n / 8000
    # speech span
    on = [i for i, e in enumerate(env) if e > 0.12]
    t0, t1 = (on[0] / 50, (on[-1] + 1) / 50) if on else (0, dur)
    words = text.split()
    weight = []
    for w in words:
        x = syl(w) * 1.0 + 0.35
        if re.search(r'[.!?]$', w): x += 1.6
        elif re.search(r'[,;:]$', w): x += 0.8
        weight.append(x)
    total = sum(weight); acc = 0; times = []
    for w in weight:
        times.append(round(t0 + (t1 - t0) * acc / total, 2)); acc += w
    return dict(src=f'assets/voice/{lid(text)}.mp3', dur=round(dur, 2), fps=50, env=env, wordTimes=times)

if __name__ == '__main__':
    os.makedirs(OUT_DIR, exist_ok=True)
    L = lines()
    todo = [t for t in L if not os.path.exists(os.path.join(OUT_DIR, lid(t) + '.mp3'))]
    print(f'{len(L)} lines, {len(todo)} to generate', flush=True)
    workers = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    with ProcessPoolExecutor(workers) as ex:
        for k, t in enumerate(ex.map(gen, todo)): print(f'  {k + 1}/{len(todo)} {t[:60]}', flush=True)
    keep = {lid(t) + '.mp3' for t in L}
    for f in os.listdir(OUT_DIR):
        if f not in keep: os.remove(os.path.join(OUT_DIR, f))
    data = {t: analyse(t) for t in L}
    with open(os.path.join(ROOT, 'js', 'voice-lines.js'), 'w') as fh:
        fh.write('// Generated by tools/build_voice.py — narration audio for every walkthrough line.\n')
        fh.write('// Voice: Kokoro-82M blend chosen to resemble Sam\'s approved recordings (not a clone).\n')
        fh.write('export const LINES = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    print('total audio %.1f s' % sum(d['dur'] for d in data.values()))
