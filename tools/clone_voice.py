# Regenerates every narration line in Sam's own voice by zero-shot cloning from his approved
# recordings (Chatterbox, MIT licence, weights from Hugging Face: ResembleAI/chatterbox).
# Each line is scored for speaker similarity against Sam's real voice (Resemblyzer); the best of
# several takes is kept. Output replaces assets/voice/*.mp3 and js/voice-lines.js.
#
# Usage (Python 3.11 env with chatterbox-tts, resemblyzer, soundfile; ffmpeg; node):
#   python tools/clone_voice.py --ref /path/sam_ref.wav [--takes 3] [--only N]
import argparse, json, os, subprocess, sys, tempfile
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from build_voice import lines, lid, analyse, OUT_DIR  # noqa: E402

def to16k(path, out):
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', path, '-ac', '1', '-ar', '16000', out], check=True)
    return out

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ref', required=True)
    ap.add_argument('--takes', type=int, default=3)
    ap.add_argument('--only', type=int, default=0, help='generate only the first N lines (trial run)')
    ap.add_argument('--exaggeration', type=float, default=0.55)
    ap.add_argument('--cfg', type=float, default=0.45)
    a = ap.parse_args()

    import torch, soundfile as sf
    from chatterbox.tts import ChatterboxTTS
    from resemblyzer import VoiceEncoder, preprocess_wav
    torch.set_num_threads(os.cpu_count() or 4)
    model = ChatterboxTTS.from_pretrained(device='cpu')
    enc = VoiceEncoder('cpu')
    tmp = tempfile.mkdtemp()
    sam = enc.embed_utterance(preprocess_wav(to16k(a.ref, os.path.join(tmp, 'ref16.wav'))))

    L = lines()
    if a.only: L = L[:a.only]
    os.makedirs(OUT_DIR, exist_ok=True)
    report = []
    for k, text in enumerate(L):
        best = None
        for t in range(a.takes):
            torch.manual_seed(1000 + t)
            wav = model.generate(text, audio_prompt_path=a.ref, exaggeration=a.exaggeration, cfg_weight=a.cfg)
            p = os.path.join(tmp, f'take{t}.wav')
            sf.write(p, wav.squeeze(0).numpy(), model.sr)
            sim = float(np.dot(sam, enc.embed_utterance(preprocess_wav(to16k(p, os.path.join(tmp, 't16.wav'))))))
            if best is None or sim > best[0]: best = (sim, p)
            if sim >= 0.85: break
        out = os.path.join(OUT_DIR, lid(text) + '.mp3')
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', best[1], '-af', 'loudnorm=I=-16:TP=-1.5,apad=pad_dur=0.12',
                        '-ac', '1', '-ar', '44100', '-b:a', '64k', out], check=True)
        report.append({'text': text, 'similarity': round(best[0], 3)})
        print(f'{k + 1}/{len(L)} sim {best[0]:.3f}  {text[:60]}', flush=True)
    data = {t: analyse(t) for t in lines() if os.path.exists(os.path.join(OUT_DIR, lid(t) + '.mp3'))}
    with open(os.path.join(ROOT, 'js', 'voice-lines.js'), 'w') as fh:
        fh.write('// Generated by tools/clone_voice.py — narration in Sam\'s cloned voice (from his approved recordings).\n')
        fh.write('export const LINES = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    sims = [r['similarity'] for r in report]
    with open(os.path.join(ROOT, 'tools', 'voice-similarity.json'), 'w') as fh:
        json.dump({'mean': round(float(np.mean(sims)), 3), 'min': min(sims), 'lines': report}, fh, indent=1)
    print('mean similarity %.3f, min %.3f' % (np.mean(sims), min(sims)))

if __name__ == '__main__':
    main()
